#!/usr/bin/env bash
# WavesOS autostart editor (terminal)
# Manages user commands between markers in configs/autostart.lua
set -euo pipefail

HYPR_DIR="${HYPR_DIR:-$HOME/.config/hypr}"
AUTOSTART="${HYPR_DIR}/configs/autostart.lua"
BACKUP="${AUTOSTART}.bak-autostart-editor"
LIST="${HYPR_DIR}/autostart-user.list"
MARK_BEGIN="-- >>> WAVESOS-USER-AUTOSTART-BEGIN"
MARK_END="-- <<< WAVESOS-USER-AUTOSTART-END"

RED='\033[0;31m'
GREEN='\033[0;32m'
CYAN='\033[0;36m'
BOLD='\033[1m'
DIM='\033[2m'
NC='\033[0m'

[[ -f "$AUTOSTART" ]] || { echo "Missing $AUTOSTART"; exit 1; }
[[ -t 0 && -t 1 ]] || { echo "Run in a terminal (kitty)."; exit 1; }

notify() {
    command -v notify-send >/dev/null 2>&1 && notify-send -t 2000 "Autostart" "$1" || true
}

pause() {
    echo
    read -r -n1 -p "Press any key..." _
    echo
}

draw_header() {
    clear
    echo -e "${BOLD}══════════════════════════════════════${NC}"
    echo -e "${BOLD}  Autostart editor${NC}"
    echo -e "${BOLD}══════════════════════════════════════${NC}"
    echo
}

ensure_list() {
    mkdir -p "$(dirname "$LIST")"
    [[ -f "$LIST" ]] || : >"$LIST"
}

# Read user commands (one per line, # comments ok)
load_cmds() {
    ensure_list
    mapfile -t CMDS < <(grep -vE '^\s*(#|$)' "$LIST" || true)
}

save_list() {
    ensure_list
    {
        echo "# WavesOS user autostart — one command per line"
        echo "# Managed by autostart-editor.sh"
        local c
        for c in "${CMDS[@]:-}"; do
            [[ -n "${c:-}" ]] && printf '%s\n' "$c"
        done
    } >"$LIST"
}

# Rewrite managed block in autostart.lua from LIST
sync_lua() {
    ensure_list
    load_cmds
    cp -p "$AUTOSTART" "$BACKUP"

    python3 - "$AUTOSTART" "$LIST" "$MARK_BEGIN" "$MARK_END" <<'PY'
import sys
path, list_path, begin, end = sys.argv[1:5]
text = open(path, encoding="utf-8").read()
cmds = []
for line in open(list_path, encoding="utf-8"):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    cmds.append(line)

block_lines = [begin, "-- auto-generated by autostart-editor.sh — do not edit this block by hand"]
for c in cmds:
    esc = c.replace("\\", "\\\\").replace('"', '\\"')
    block_lines.append(f'    hl.exec_cmd("{esc}")')
block_lines.append(end)
block = "\n".join(block_lines)

if begin in text and end in text:
    import re
    text = re.sub(
        re.escape(begin) + r".*?" + re.escape(end),
        block,
        text,
        count=1,
        flags=re.S,
    )
else:
    # append markers at end of file if missing
    text = text.rstrip() + "\n\n" + block + "\n"

open(path, "w", encoding="utf-8").write(text)
PY
}

list_cmds() {
    load_cmds
    draw_header
    if ((${#CMDS[@]} == 0)); then
        echo -e "${DIM}(no user autostart commands yet)${NC}"
    else
        local i=0
        for c in "${CMDS[@]}"; do
            i=$((i + 1))
            printf "  ${CYAN}%2d${NC}  %s\n" "$i" "$c"
        done
    fi
    echo
}

add_cmd() {
    draw_header
    echo -e "${BOLD}Command to run at Hyprland start${NC}"
    echo -e "${DIM}Examples:${NC}"
    echo "  ~/.config/hypr/scripts/eww-watchdog.sh &"
    echo "  nm-applet"
    echo "  sleep 2 && ~/.config/hypr/scripts/foo.sh"
    echo
    read -r -p "Command: " cmd
    [[ -z "$cmd" ]] && return

    load_cmds
    CMDS+=("$cmd")
    save_list
    sync_lua
    echo -e "${GREEN}Added. Will run on next Hyprland start / session.${NC}"
    echo -e "${DIM}Note: already-running session is not re-executing all autostart lines.${NC}"
    notify "Autostart added"
    pause
}

remove_cmd() {
    load_cmds
    ((${#CMDS[@]})) || { echo "Nothing to remove."; pause; return; }

    list_cmds
    read -r -p "Number to remove (empty = back): " num
    [[ -z "$num" ]] && return
    [[ "$num" =~ ^[0-9]+$ ]] || return
    (( num >= 1 && num <= ${#CMDS[@]} )) || return

    local cmd="${CMDS[$((num - 1))]}"

    clear
    echo
    echo -e "${RED}${BOLD}"
    cat <<'WARN'
╔══════════════════════════════════════════════════════════════╗
║                                                              ║
║   WARNING: REMOVE AUTOSTART COMMAND                          ║
║                                                              ║
║   Type exactly:  DELETE                                      ║
║   (anything else cancels)                                    ║
║                                                              ║
╚══════════════════════════════════════════════════════════════╝
WARN
    echo -e "${NC}"
    echo -e "  Command: ${BOLD}${cmd}${NC}"
    echo
    read -r -p "> " confirm
    if [[ "$confirm" != "DELETE" ]]; then
        echo -e "${GREEN}Cancelled.${NC}"
        pause
        return
    fi

    local -a NEW=()
    local i=0
    for c in "${CMDS[@]}"; do
        i=$((i + 1))
        [[ $i -eq $num ]] && continue
        NEW+=("$c")
    done
    CMDS=("${NEW[@]}")
    save_list
    sync_lua
    echo -e "${GREEN}Removed.${NC}"
    notify "Autostart removed"
    pause
}

run_now() {
    load_cmds
    ((${#CMDS[@]})) || { echo "No user commands."; pause; return; }
    list_cmds
    read -r -p "Run which number now? (empty = back): " num
    [[ -z "$num" ]] && return
    [[ "$num" =~ ^[0-9]+$ ]] || return
    (( num >= 1 && num <= ${#CMDS[@]} )) || return
    local cmd="${CMDS[$((num - 1))]}"
    echo -e "${CYAN}Running:${NC} $cmd"
    bash -lc "$cmd" &
    echo -e "${GREEN}Started in background.${NC}"
    pause
}

# --- main ---
ensure_list
# ensure markers exist / sync current list into lua
if ! grep -Fq -- "WAVESOS-USER-AUTOSTART-BEGIN" "$AUTOSTART" 2>/dev/null; then
    echo -e "${RED}Markers missing in autostart.lua${NC}"
    echo "Add these inside hl.on(\"hyprland.start\", function() ... end):"
    echo "  $MARK_BEGIN"
    echo "  $MARK_END"
    pause
fi
sync_lua 2>/dev/null || true

while true; do
    draw_header
    load_cmds
    echo -e "  User autostart entries: ${BOLD}${#CMDS[@]}${NC}"
    echo
    echo "  1) List commands"
    echo "  2) Add command"
    echo "  3) Remove command"
    echo "  4) Run one now (test)"
    echo "  5) Open autostart.lua"
    echo "  q) Quit"
    echo
    read -r -p "Select: " choice
    case "$choice" in
        1) list_cmds; pause ;;
        2) add_cmd ;;
        3) remove_cmd ;;
        4) run_now ;;
        5) "${EDITOR:-nano}" "$AUTOSTART" ;;
        q|Q) break ;;
    esac
done

clear
echo "Done."

